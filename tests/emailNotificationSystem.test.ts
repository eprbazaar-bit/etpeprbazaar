function createMemoryNotificationStore(seed: {
  staffUids?: string[];
  buyers?: FixtureParticipant[];
  sellers?: FixtureParticipant[];
  buyerRequirements?: StoredListingRecord[];
  sellerListings?: StoredListingRecord[];
}) {
  const staffSet = new Set(seed.staffUids || ['staff-admin-1']);
  const buyers = [...(seed.buyers || [])];
  const sellers = [...(seed.sellers || [])];
  const buyerRequirements = [...(seed.buyerRequirements || [])];
  const sellerListings = [...(seed.sellerListings || [])];
  const deliveryLogs = new Map<string, StoredEmailDeliveryLog>();
  const userNotifications = new Map<string, StoredUserNotification>();

  const store: NotificationStore = {
    async isStaffUser(uid, email) {
      return staffSet.has(uid) || email?.toLowerCase() === 'ajaykumartiwari609@gmail.com';
    },

    async isActiveUserAccount(uid, role) {
      const list = role === 'buyer' ? buyers : sellers;
      const found = list.find((p) => p.uid === uid);
      return Boolean(found && found.status === 'Active');
    },

    async getListing(listingId, type) {
      const list = type === 'buyer_requirement' ? buyerRequirements : sellerListings;
      return list.find((item) => item.id === listingId) || null;
    },

    async getParticipantLocation(uid, role) {
      const list = role === 'buyer' ? buyers : sellers;
      const found = list.find((p) => p.uid === uid);
      if (!found) return 'India';
      const parts = [found.city, found.state].map((s) => (s || '').trim()).filter(Boolean);
      return parts.length > 0 ? parts.join(', ') : 'India';
    },

    async findMatchingRecipients(recipientRole, categoryId, categoryName, excludeUid) {
      const list = recipientRole === 'buyer' ? buyers : sellers;
      const activityList = recipientRole === 'buyer' ? buyerRequirements : sellerListings;
      const implicitUids = new Set(
        activityList.filter((l) => l.categoryId === categoryId).map((l) => l.ownerUid)
      );

      return list.filter((p) => {
        if (p.status !== 'Active') return false;
        if (p.uid === excludeUid) return false;
        if (p.emailNotificationsEnabled === false) return false;
        const dealing = p.dealingCategories || [];
        const explicitMatch =
          dealing.length > 0 &&
          (dealing.includes(categoryId) ||
            dealing.some((c) => c.trim().toLowerCase() === categoryName.trim().toLowerCase()));
        const implicitMatch = dealing.length === 0 && implicitUids.has(p.uid);
        return explicitMatch || implicitMatch;
      });
    },

    async getDeliveryLog(notificationId) {
      return deliveryLogs.get(notificationId) || null;
    },

    async listFailedDeliveryLogs(notificationId, maxAttempts = 5) {
      if (notificationId) {
        const single = deliveryLogs.get(notificationId);
        return single && single.status === 'failed' ? [single] : [];
      }
      return Array.from(deliveryLogs.values()).filter(
        (l) => l.status === 'failed' && l.attemptCount < maxAttempts
      );
    },

    async upsertDeliveryLog(log) {
      deliveryLogs.set(log.notificationId, { ...log });
    },

    async upsertUserNotification(notif) {
      userNotifications.set(notif.id, { ...notif });
    },
  };

  return { store, deliveryLogs, userNotifications };
}

