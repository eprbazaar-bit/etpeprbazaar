interface CapturedSmtpMessage {
  mailFrom: string;
  rcptTo: string[];
  rawData: string;
  decodedBody: string;
  subject: string;
}

function decodeMimeQuotedPrintableOrBase64(raw: string): string {
  // Handle multipart or single-part MIME generated by nodemailer
  const parts = raw.split(/\r?\n--[^\r\n]+/);
  const decodedChunks: string[] = [];
  for (const part of parts) {
    const headerEnd = part.search(/\r?\n\r?\n/);
    if (headerEnd === -1) continue;
    const headers = part.slice(0, headerEnd);
    const body = part.slice(headerEnd).replace(/^\r?\n\r?\n/, '');
    if (/Content-Transfer-Encoding:\s*base64/i.test(headers)) {
      decodedChunks.push(Buffer.from(body.replace(/\s+/g, ''), 'base64').toString('utf8'));
    } else if (/Content-Transfer-Encoding:\s*quoted-printable/i.test(headers)) {
      const cleaned = body
        .replace(/=\r?\n/g, '')
        .replace(/=([0-9A-Fa-f]{2})/g, (_, hex: string) => String.fromCharCode(parseInt(hex, 16)));
      decodedChunks.push(cleaned);
    } else {
      decodedChunks.push(body);
    }
  }
  return decodedChunks.length > 0 ? decodedChunks.join('\n') : raw;
}

function decodeRfc2047Subject(rawHeaders: string): string {
  const unfolded = rawHeaders.replace(/\r?\n[ \t]+/g, ' ');
  const match = unfolded.match(/^Subject:\s*(.+)$/im);
  if (!match) return '';
  const rawVal = match[1].trim();
  const decodedParts: string[] = [];
  const tokenRegex = /=\?UTF-8\?([QB])\?([^?]+)\?=/gi;
  let lastIdx = 0;
  let m: RegExpExecArray | null;
  while ((m = tokenRegex.exec(rawVal)) !== null) {
    if (m.index > lastIdx) {
      const gap = rawVal.slice(lastIdx, m.index);
      if (gap.trim()) decodedParts.push(gap);
    }
    const enc = m[1].toUpperCase();
    const payload = m[2];
    if (enc === 'B') {
      decodedParts.push(Buffer.from(payload, 'base64').toString('utf8'));
    } else {
      const bytes: number[] = [];
      const qStr = payload.replace(/_/g, ' ');
      for (let i = 0; i < qStr.length; i++) {
        if (qStr[i] === '=' && /^[0-9A-Fa-f]{2}$/.test(qStr.slice(i + 1, i + 3))) {
          bytes.push(parseInt(qStr.slice(i + 1, i + 3), 16));
          i += 2;
        } else {
          bytes.push(...Buffer.from(qStr[i], 'utf8'));
        }
      }
      decodedParts.push(Buffer.from(bytes).toString('utf8'));
    }
    lastIdx = tokenRegex.lastIndex;
  }
  if (decodedParts.length === 0) return rawVal;
  if (lastIdx < rawVal.length) {
    const tail = rawVal.slice(lastIdx);
    if (tail.trim()) decodedParts.push(tail);
  }
  return decodedParts.join('');
}

async function startLocalSmtpServer(options?: { failNextRcpt?: boolean }): Promise<{
  port: number;
  messages: CapturedSmtpMessage[];
  setFailMode: (fail: boolean) => void;
  close: () => Promise<void>;
}> {
  const messages: CapturedSmtpMessage[] = [];
  let shouldFail = Boolean(options?.failNextRcpt);

  const server = net.createServer((socket) => {
    socket.write('220 localhost ESMTP EPR-Bazaar-Test\r\n');
    let buffer = '';
    let inData = false;
    let currentMailFrom = '';
    let currentRcptTo: string[] = [];
    let currentData = '';

    const processLine = (line: string) => {
      if (inData) {
        if (line === '.') {
          inData = false;
          const headerSection = currentData.split(/\r?\n\r?\n/)[0] || currentData;
          const decodedBody = decodeMimeQuotedPrintableOrBase64(currentData);
          messages.push({
            mailFrom: currentMailFrom,
            rcptTo: [...currentRcptTo],
            rawData: currentData,
            decodedBody,
            subject: decodeRfc2047Subject(headerSection),
          });
          currentData = '';
          socket.write('250 2.0.0 OK queued\r\n');
          return;
        }
        currentData += (line.startsWith('..') ? line.slice(1) : line) + '\r\n';
        return;
      }

      const upper = line.toUpperCase();
      if (upper.startsWith('EHLO') || upper.startsWith('HELO')) {
        socket.write('250-localhost\r\n250 SIZE 10485760\r\n');
      } else if (upper.startsWith('MAIL FROM:')) {
        currentMailFrom = line.slice(10).trim();
        currentRcptTo = [];
        if (shouldFail) {
          socket.write('451 4.7.1 Temporary SMTP relay error\r\n');
        } else {
          socket.write('250 2.1.0 OK\r\n');
        }
      } else if (upper.startsWith('RCPT TO:')) {
        currentRcptTo.push(line.slice(8).trim());
        socket.write('250 2.1.5 OK\r\n');
      } else if (upper === 'DATA') {
        inData = true;
        currentData = '';
        socket.write('354 Start mail input; end with <CRLF>.<CRLF>\r\n');
      } else if (upper === 'RSET') {
        currentMailFrom = '';
        currentRcptTo = [];
        socket.write('250 2.0.0 OK\r\n');
      } else if (upper === 'QUIT') {
        socket.write('221 2.0.0 Bye\r\n');
        socket.end();
      } else {
        socket.write('250 OK\r\n');
      }
    };

    socket.on('data', (chunk) => {
      buffer += chunk.toString('utf8');
      let idx = buffer.indexOf('\r\n');
      while (idx !== -1) {
        const line = buffer.slice(0, idx);
        buffer = buffer.slice(idx + 2);
        processLine(line);
        idx = buffer.indexOf('\r\n');
      }
    });
  });

  await new Promise<void>((resolve) => {
    server.listen(0, '127.0.0.1', () => resolve());
  });
  const addr = server.address() as net.AddressInfo;

  return {
    port: addr.port,
    messages,
    setFailMode: (fail: boolean) => {
      shouldFail = fail;
    },
    close: () =>
      new Promise<void>((resolve, reject) => {
        server.close((err) => (err ? reject(err) : resolve()));
      }),
  };
}

